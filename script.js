function render() {
  const t = TEXT[state.lang];
  document.documentElement.lang = state.lang;
  $("#lang").textContent = state.lang === "fr" ? "EN" : "FR";

  document.querySelectorAll("[data-i]").forEach((el) => {
    if (typeof t[el.dataset.i] === "string") el.textContent = t[el.dataset.i];
  });
  $("#wishBtn").textContent = state.candlesLit ? t.wishB : t.wishBRelight;
  $("#cd").textContent =
    new Date().getDate() === 26 ? t.countdown[0] : t.countdown[1];

  $("#letter").innerHTML =
    t.letter.map((p) => `<p>${p}</p>`).join("") + `<p class="sig">${t.sig}</p>`;
  $("#lyrics").innerHTML = TEXT.fr.lyrics
    .map(
      (l) =>
        `<div class="line"><b>${l[0]}</b>${state.lang === "en" ? `<small>${l[1]}</small>` : ""}</div>`,
    )
    .join("");

  $("#track").innerHTML = t.slides
    .map(
      (m, i) =>
        `<figure class="slide">
          <div class="heart-frame">
            <img loading="lazy" src="fotos/foto${i + 1}.jpg" alt="">
          </div>
          <p>${m}</p>
        </figure>`,
    )
    .join("");

  $("#dots").innerHTML = t.slides
    .map((_, i) => `<button data-go="${i}" aria-label="${i + 1}"></button>`)
    .join("");
  goTo(state.slide);

  $("#cards").innerHTML = t.reasons
    .map((r, i) => {
      const rank = CARD_RANKS[i % CARD_RANKS.length];
      return `
        <div class="card">
          <div>
            <div class="face front">
              <span class="suit-top">${rank}</span>
              <span class="center-heart">♥</span>
              <span class="suit-bot">${rank}</span>
            </div>
            <div class="face back">
              <span class="suit-top">${rank}</span>
              <span>${r}</span>
              <span class="suit-bot">${rank}</span>
            </div>
          </div>
        </div>`;
    })
    .join("");

  observeLetter();
}

function observeLetter() {
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((e) => {
        if (e.isIntersecting) {
          e.target.classList.add("in");
          io.unobserve(e.target);
        }
      });
    },
    { threshold: 0.3 },
  );
  document.querySelectorAll(".letter p").forEach((p) => io.observe(p));
}

