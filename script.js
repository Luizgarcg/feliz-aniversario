function goTo(n) {
  const total = TEXT[state.lang].slides.length;
  state.slide = ((n % total) + total) % total;
  const track = $("#track");
  if (track) {
    track.style.transform = `translate3d(-${state.slide * 100}%, 0, 0)`;
  }
  document
    .querySelectorAll("#dots button")
    .forEach((d, i) => d.classList.toggle("on", i === state.slide));
}

function restartAutoplay() {
  clearInterval(state.auto);
  state.auto = setInterval(() => goTo(state.slide + 1), 6000);
}

function bindCarousel() {
  $("#prev").onclick = () => {
    goTo(state.slide - 1);
    restartAutoplay();
  };
  $("#next").onclick = () => {
    goTo(state.slide + 1);
    restartAutoplay();
  };
  $("#dots").onclick = (e) => {
    const b = e.target.closest("button");
    if (b) {
      goTo(+b.dataset.go);
      restartAutoplay();
    }
  };
  let x0 = null;
  const car = $("#carousel");
  car.addEventListener("touchstart", (e) => (x0 = e.touches[0].clientX), {
    passive: true,
  });
  car.addEventListener("touchend", (e) => {
    if (x0 === null) return;
    const dx = e.changedTouches[0].clientX - x0;
    if (Math.abs(dx) > 40) {
      goTo(state.slide + (dx < 0 ? 1 : -1));
      restartAutoplay();
    }
    x0 = null;
  });
  restartAutoplay();
}

