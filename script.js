let ytPlayer = null,
  ytReady = false,
  musicOn = false;

function setMusicIcon() {
  const icon = $("#musIcon");
  if (!icon) return;
  icon.style.opacity = musicOn ? "1" : "0.55";
  $("#mus").style.borderColor = musicOn
    ? "rgba(246, 239, 230, 0.8)"
    : "rgba(246, 239, 230, 0.28)";
}

function loadYouTube() {
  if (!ytId) return;
  const s = document.createElement("script");
  s.src = "https://www.youtube.com/iframe_api";
  document.head.appendChild(s);
  window.onYouTubeIframeAPIReady = () => {
    ytPlayer = new YT.Player("yt", {
      width: "200",
      height: "200",
      videoId: ytId,
      playerVars: { playsinline: 1, controls: 0, loop: 1, playlist: ytId },
      events: {
        onReady: () => {
          ytReady = true;
          if (musicOn) ytPlayer.playVideo();
        },
        onStateChange: (e) => {
          if (e.data === YT.PlayerState.ENDED) ytPlayer.playVideo();
        },
      },
    });
  };
}

const music = {
  play() {
    musicOn = true;
    if (ytId) {
      if (ytReady) ytPlayer.playVideo();
    } else
      $("#bgm")
        .play()
        .catch(() => {});
    setMusicIcon();
  },
  pause() {
    musicOn = false;
    if (ytId) {
      if (ytReady) ytPlayer.pauseVideo();
    } else $("#bgm").pause();
    setMusicIcon();
  },
};

function toggleMusic() {
  musicOn ? music.pause() : music.play();
}

function toggleSinging() {
  const lines = document.querySelectorAll("#lyrics .line");
  const song = $("#song");
  if (state.singing) {
    stopSinging(lines, song);
    return;
  }
  state.singing = true;
  music.pause();
  song.currentTime = 0;
  song.play().catch(() => {});
  lines.forEach((line, i) => {
    state.timers.push(
      setTimeout(() => {
        lines.forEach((l) => l.classList.remove("on"));
        line.classList.add("on");
        const r = line.getBoundingClientRect();
        burst(r.left + r.width / 2, r.top, 8);
      }, i * 2300),
    );
  });
  state.timers.push(
    setTimeout(() => stopSinging(lines, song), lines.length * 2300),
  );
}

function stopSinging(lines, song) {
  state.timers.forEach(clearTimeout);
  state.timers = [];
  state.singing = false;
  lines.forEach((l) => l.classList.remove("on"));
  song.pause();
}

