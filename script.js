const fireworks = [];
const vectorBursts = [];

function drawCanvasHeart(ctx, x, y, size, color, rotation = 0) {
  ctx.save();
  ctx.translate(x, y);
  ctx.rotate(rotation);
  ctx.fillStyle = color;
  ctx.beginPath();
  ctx.moveTo(0, size * 0.3);
  ctx.bezierCurveTo(-size * 0.5, -size * 0.3, -size, size * 0.1, 0, size);
  ctx.bezierCurveTo(size, size * 0.1, size * 0.5, -size * 0.3, 0, size * 0.3);
  ctx.fill();
  ctx.restore();
}

function burst(x, y, n = 18) {
  const colors = ["#b92328", "#f6efe6", "#d6686c", "#8f171c"];
  for (let i = 0; i < n; i++) {
    const angle = Math.random() * Math.PI * 2;
    const speed = 1.8 + Math.random() * 4.5;
    vectorBursts.push({
      x,
      y,
      vx: Math.cos(angle) * speed,
      vy: Math.sin(angle) * speed - 1.5,
      size: 6 + Math.random() * 7,
      rot: Math.random() * Math.PI * 2,
      vRot: (Math.random() - 0.5) * 0.12,
      alpha: 1,
      color: colors[i % colors.length],
    });
  }
}

function launchHeartFirework(cxX, cxY) {
  const count = 90;
  const palette = ["#b92328", "#f6efe6", "#d6686c", "#fffaf2", "#8f171c"];
  for (let i = 0; i < count; i++) {
    const angle = (Math.PI * 2 * i) / count;
    const hx = 16 * Math.pow(Math.sin(angle), 3);
    const hy = -(
      13 * Math.cos(angle) -
      5 * Math.cos(2 * angle) -
      2 * Math.cos(3 * angle) -
      Math.cos(4 * angle)
    );
    const speed = 0.28 + Math.random() * 0.08;
    fireworks.push({
      x: cxX,
      y: cxY,
      vx: hx * speed,
      vy: hy * speed,
      alpha: 1,
      decay: 0.011 + Math.random() * 0.006,
      color: palette[i % palette.length],
      size: 2.2 + Math.random() * 1.8,
      history: [],
    });
  }
}

function startBackground() {
  const cv = $("#fx"),
    cx = cv.getContext("2d");
  const bCv = $("#burstCanvas"),
    bCx = bCv.getContext("2d");
  let W, H;
  const resize = () => {
    W = cv.width = bCv.width = innerWidth;
    H = cv.height = bCv.height = innerHeight;
  };
  resize();
  addEventListener("resize", resize);

  const petalCount = innerWidth < 640 ? 22 : 38;
  const petals = Array.from({ length: petalCount }, () => ({
    x: Math.random() * innerWidth,
    y: Math.random() * innerHeight,
    vy: 0.35 + Math.random() * 0.55,
    swayAmp: 0.4 + Math.random() * 0.8,
    swayFreq: 0.01 + Math.random() * 0.015,
    phase: Math.random() * Math.PI * 2,
    size: 5 + Math.random() * 6,
    rot: Math.random() * Math.PI * 2,
    vRot: (Math.random() - 0.5) * 0.02,
    isHeart: Math.random() > 0.68,
    alpha: 0.14 + Math.random() * 0.22,
  }));

  let t = 0;
  const trail = [];
  const maxPoints = 190;

  function heartFormula(angle, scale) {
    const x = 16 * Math.pow(Math.sin(angle), 3);
    const y = -(
      13 * Math.cos(angle) -
      5 * Math.cos(2 * angle) -
      2 * Math.cos(3 * angle) -
      Math.cos(4 * angle)
    );
    return { x: W / 2 + x * scale, y: H / 2 + y * scale };
  }

  (function loop() {
    cx.clearRect(0, 0, W, H);
    bCx.clearRect(0, 0, W, H);

    petals.forEach((p) => {
      p.phase += p.swayFreq;
      p.y += p.vy;
      p.x += Math.sin(p.phase) * p.swayAmp;
      p.rot += p.vRot;

      if (p.y > H + 20) {
        p.y = -20;
        p.x = Math.random() * W;
      }

      cx.save();
      cx.globalAlpha = p.alpha;
      if (p.isHeart) {
        drawCanvasHeart(cx, p.x, p.y, p.size * 1.1, "#b92328", p.rot * 0.3);
      } else {
        cx.translate(p.x, p.y);
        cx.rotate(p.rot);
        cx.fillStyle = "#9e1b1f";
        cx.beginPath();
        cx.ellipse(0, 0, p.size, p.size * 0.55, 0, 0, Math.PI * 2);
        cx.fill();
      }
      cx.restore();
    });

    const scale = Math.min(W, H) * 0.021;
    const pt = heartFormula(t, scale);
    trail.push(pt);
    if (trail.length > maxPoints) trail.shift();
    t += 0.036;

    cx.save();
    for (let i = 0; i < trail.length; i++) {
      const alpha = (i / trail.length) * 0.22;
      cx.strokeStyle = `rgba(185, 35, 40, ${alpha})`;
      cx.lineWidth = 1;
      cx.beginPath();
      cx.moveTo(W / 2, H / 2);
      cx.lineTo(trail[i].x, trail[i].y);
      cx.stroke();
    }

    if (trail.length > 1) {
      cx.beginPath();
      cx.strokeStyle = "rgba(246, 239, 230, 0.62)";
      cx.lineWidth = 1.6;
      cx.moveTo(trail[0].x, trail[0].y);
      for (let i = 1; i < trail.length; i++) {
        cx.lineTo(trail[i].x, trail[i].y);
      }
      cx.stroke();

      const head = trail[trail.length - 1];
      cx.beginPath();
      cx.fillStyle = "#fbf4eb";
      cx.shadowColor = "#b92328";
      cx.shadowBlur = 12;
      cx.arc(head.x, head.y, 2.8, 0, Math.PI * 2);
      cx.fill();
    }
    cx.restore();

    for (let i = fireworks.length - 1; i >= 0; i--) {
      const f = fireworks[i];
      f.history.push({ x: f.x, y: f.y });
      if (f.history.length > 7) f.history.shift();

      f.x += f.vx;
      f.y += f.vy;
      f.vx *= 0.96;
      f.vy = f.vy * 0.96 + 0.045;
      f.alpha -= f.decay;

      if (f.alpha <= 0) {
        fireworks.splice(i, 1);
        continue;
      }

      cx.save();
      cx.globalAlpha = f.alpha;
      if (f.history.length > 1) {
        cx.beginPath();
        cx.strokeStyle = f.color;
        cx.lineWidth = f.size * 0.8;
        cx.moveTo(f.history[0].x, f.history[0].y);
        for (let k = 1; k < f.history.length; k++) {
          cx.lineTo(f.history[k].x, f.history[k].y);
        }
        cx.stroke();
      }
      cx.beginPath();
      cx.fillStyle = f.color;
      cx.arc(f.x, f.y, f.size, 0, Math.PI * 2);
      cx.fill();
      cx.restore();
    }

    for (let i = vectorBursts.length - 1; i >= 0; i--) {
      const b = vectorBursts[i];
      b.x += b.vx;
      b.y += b.vy;
      b.vy += 0.08;
      b.rot += b.vRot;
      b.alpha -= 0.018;
      if (b.alpha <= 0) {
        vectorBursts.splice(i, 1);
        continue;
      }
      bCx.save();
      bCx.globalAlpha = b.alpha;
      drawCanvasHeart(bCx, b.x, b.y, b.size, b.color, b.rot);
      bCx.restore();
    }

    requestAnimationFrame(loop);
  })();
}

function startWaveform() {
  const cv = $("#wave");
  if (!cv) return;
  const cx = cv.getContext("2d");
  let phase = 0;

  function resizeWave() {
    cv.width = cv.offsetWidth * (window.devicePixelRatio || 1);
    cv.height = cv.offsetHeight * (window.devicePixelRatio || 1);
  }
  resizeWave();
  addEventListener("resize", resizeWave);

  (function drawWave() {
    const W = cv.width,
      H = cv.height;
    cx.clearRect(0, 0, W, H);

    const active = state.singing || musicOn;
    const ampBase = active ? H * 0.34 : H * 0.08;
    phase += active ? 0.09 : 0.025;

    const waves = [
      { color: "rgba(185, 35, 40, 0.88)", freq: 0.018, speed: 1, width: 2.4 },
      {
        color: "rgba(246, 239, 230, 0.68)",
        freq: 0.026,
        speed: -1.4,
        width: 1.7,
      },
      {
        color: "rgba(214, 104, 108, 0.45)",
        freq: 0.012,
        speed: 0.7,
        width: 1.4,
      },
    ];

    waves.forEach((w) => {
      cx.beginPath();
      cx.strokeStyle = w.color;
      cx.lineWidth = w.width;
      for (let x = 0; x <= W; x += 4) {
        const norm = x / W;
        const envelope = Math.sin(norm * Math.PI);
        const y =
          H / 2 + Math.sin(x * w.freq + phase * w.speed) * ampBase * envelope;
        if (x === 0) cx.moveTo(x, y);
        else cx.lineTo(x, y);
      }
      cx.stroke();
    });

    requestAnimationFrame(drawWave);
  })();
}

